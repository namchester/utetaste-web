-- V1 used PostgreSQL-generated names; locate only its role/branch CHECK constraints.
DO $$ DECLARE c RECORD; BEGIN
  FOR c IN SELECT conname FROM pg_constraint
    WHERE conrelid='app_users'::regclass AND contype='c'
      AND pg_get_constraintdef(oid) LIKE '%role%'
  LOOP EXECUTE format('ALTER TABLE app_users DROP CONSTRAINT %I',c.conname); END LOOP;
END $$;
