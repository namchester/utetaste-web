CREATE TABLE email_otps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES app_users(id),
  purpose VARCHAR(30) NOT NULL CHECK(purpose IN ('VERIFY_EMAIL','LINK_EMAIL','RESET_PASSWORD')),
  target_email VARCHAR(254) NOT NULL,
  code_hash VARCHAR(64) NOT NULL,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 5),
  consumed BOOLEAN NOT NULL DEFAULT FALSE,
  issued_version INTEGER NOT NULL DEFAULT 0,
  reset_hash VARCHAR(64),
  reset_expires_at TIMESTAMP WITH TIME ZONE,
  UNIQUE(user_id,purpose), UNIQUE(reset_hash)
);
CREATE INDEX idx_email_otps_expiry ON email_otps(expires_at);
