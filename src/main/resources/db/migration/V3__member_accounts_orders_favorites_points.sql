-- Additive only. Legacy users have no invented creation date; legacy orders remain unowned.
ALTER TABLE app_users ADD COLUMN phone VARCHAR(20);
ALTER TABLE app_users ADD COLUMN created_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE app_users ADD CONSTRAINT ck_member_phone CHECK(phone IS NULL OR phone ~ '^\+?[0-9]{8,15}$');
ALTER TABLE food_orders ADD COLUMN customer_id BIGINT REFERENCES app_users(id);
CREATE INDEX idx_orders_customer_created ON food_orders(customer_id,created_at DESC,id DESC) WHERE customer_id IS NOT NULL;

CREATE TABLE member_favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    dish_id BIGINT NOT NULL REFERENCES dishes(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_member_favorite UNIQUE(user_id,dish_id)
);
CREATE INDEX idx_member_favorites_created ON member_favorites(user_id,created_at DESC,id DESC);

-- Ledger only. No automatic spend allocation or point credit is enabled by this migration.
CREATE TABLE member_point_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    invoice_id BIGINT REFERENCES invoices(id),
    reference_key VARCHAR(100) NOT NULL UNIQUE,
    points INTEGER NOT NULL CHECK(points<>0),
    reason VARCHAR(200) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_member_points_created ON member_point_entries(user_id,created_at DESC,id DESC);
